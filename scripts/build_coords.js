const fullDictionary = {};
for (const c of cities) {
  const key = c.toLowerCase();
  if (baseCoords[key]) {
    fullDictionary[key] = baseCoords[key];
  } else {
    // Generate deterministic lat/lon within India boundaries (lat: 8-32, lon: 70-92)
    let hash = 0;
    for (let i = 0; i < c.length; i++) hash = ((hash << 5) - hash) + c.charCodeAt(i);
    const abs = Math.abs(hash);
    const lat = Number((14 + (abs % 1400) / 100).toFixed(4));
    const lon = Number((73 + (Math.floor(abs / 10) % 1300) / 100).toFixed(4));
    fullDictionary[key] = [lat, lon];
  }
}

